/// Decodes a hex string, ignoring whitespace and newlines.
func bytes(fromHex hex: String) -> [UInt8] {
    let digits = Array(hex.unicodeScalars.filter { !$0.properties.isWhitespace })
    precondition(digits.count.isMultiple(of: 2), "odd number of hex digits")
    return stride(from: 0, to: digits.count, by: 2).map {
        UInt8(String(String.UnicodeScalarView(digits[$0 ... $0 + 1])), radix: 16)!
    }
}
